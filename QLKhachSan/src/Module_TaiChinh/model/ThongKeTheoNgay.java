package Module_TaiChinh.model;

public class ThongKeTheoNgay {

    private String ngayLap;
    private int soHoaDon;
    private double doanhThu;
    private double thucThu;
    private double conNo;

    public ThongKeTheoNgay() {
    }

    public String getNgayLap() {
        return ngayLap;
    }

    public void setNgayLap(String ngayLap) {
        this.ngayLap = ngayLap;
    }

    public int getSoHoaDon() {
        return soHoaDon;
    }

    public void setSoHoaDon(int soHoaDon) {
        this.soHoaDon = soHoaDon;
    }

    public double getDoanhThu() {
        return doanhThu;
    }

    public void setDoanhThu(double doanhThu) {
        this.doanhThu = doanhThu;
    }

    public double getThucThu() {
        return thucThu;
    }

    public void setThucThu(double thucThu) {
        this.thucThu = thucThu;
    }

    public double getConNo() {
        return conNo;
    }

    public void setConNo(double conNo) {
        this.conNo = conNo;
    }
}
