package Module_TaiChinh.model;

public class ThongKeTaiChinh {

    private int soHoaDon;
    private int soDaThanhToan;
    private int soChuaThanhToan;
    private double tongDoanhThu;
    private double tongThucThu;
    private double tongConNo;

    public ThongKeTaiChinh() {
    }

    public int getSoHoaDon() {
        return soHoaDon;
    }

    public void setSoHoaDon(int soHoaDon) {
        this.soHoaDon = soHoaDon;
    }

    public int getSoDaThanhToan() {
        return soDaThanhToan;
    }

    public void setSoDaThanhToan(int soDaThanhToan) {
        this.soDaThanhToan = soDaThanhToan;
    }

    public int getSoChuaThanhToan() {
        return soChuaThanhToan;
    }

    public void setSoChuaThanhToan(int soChuaThanhToan) {
        this.soChuaThanhToan = soChuaThanhToan;
    }

    public double getTongDoanhThu() {
        return tongDoanhThu;
    }

    public void setTongDoanhThu(double tongDoanhThu) {
        this.tongDoanhThu = tongDoanhThu;
    }

    public double getTongThucThu() {
        return tongThucThu;
    }

    public void setTongThucThu(double tongThucThu) {
        this.tongThucThu = tongThucThu;
    }

    public double getTongConNo() {
        return tongConNo;
    }

    public void setTongConNo(double tongConNo) {
        this.tongConNo = tongConNo;
    }
}
